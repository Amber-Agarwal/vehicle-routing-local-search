State generate_randomized_initial_state() {
    State state;
    state.helis.resize(H);

    vector<int> order(V);
    iota(order.begin(), order.end(), 0);

    std::random_device rd;
    std::mt19937 g(rd());
    std::shuffle(order.begin(), order.end(), g);

    for (int h=0; h<H; h++) {
        vector<int> assigned;
        for (int v: order) if (rand()%H==h) assigned.push_back(v);
        if (assigned.empty()) continue;

        std::shuffle(assigned.begin(), assigned.end(), g);

        vector<vector<int>> trips;
        vector<int> cur;
        double cap=0;
        for (int v: assigned) {
            if (cap > helis[h].w_cap*0.8 && !cur.empty()) {
                trips.push_back(cur); cur.clear(); cap=0;
            }
            cur.push_back(v);
            cap += villages[v].n*5;
        }
        if (!cur.empty()) trips.push_back(cur);

        for (auto& tv: trips) {
            two_opt_people_weighted(tv, helis[h].home_city);

            Trip trip;
            double cap_left = helis[h].w_cap;
            for (int v: tv) {
                Delivery del = allocate_packages(v, cap_left);
                if (del.d+del.p+del.o > 0) {
                    trip.stops.push_back(del);
                    cap_left -= del.d*w_d + del.p*w_p + del.o*w_o;
                }
                if (cap_left <= 0) break;
            }
            fill_trip_data(h,trip);
            state.helis[h].trips.push_back(trip);
        }
        fill_helicopter_data(state.helis[h]);
    }
    fill_delivered_totals(state);
    obj_func(state);
    return state;
}


// RECOMMENDED: Use Strategy 1 (Greedy Nearest-Neighbor with Demand Prioritization)
State generate_initial_state() {
    // check objective function from all start states and use the best one
    State best_state = generate_greedy_initial_state();
    double best_objective = obj_func(best_state);

    State current_state;

    current_state = generate_cluster_initial_state();
    double current_objective = obj_func(current_state);
    if (current_objective > best_objective) {
        best_objective = current_objective;
        best_state = current_state;
    }

    current_state = generate_simple_initial_state();
    current_objective = obj_func(current_state);
    if (current_objective > best_objective) {
        best_objective = current_objective;
        best_state = current_state;
    }

    current_state = generate_demand_weighted_initial_state();
    current_objective = obj_func(current_state);
    if (current_objective > best_objective) {
        best_objective = current_objective;
        best_state = current_state;
    }

    return best_state;
}

//Generate neighbours (simple)

double village_value(int v_idx, const array<int,3>& delivered) {
    int people = villages[v_idx].n;
    int food_limit = 9 * people;

    int perishable = delivered[1];
    int dry        = delivered[0];
    int other      = delivered[2];

    int total_food = perishable + dry;
    int useful_food = min(total_food, food_limit);

    double val = 0.0;
    if (useful_food <= perishable) {
        val += useful_food * v_p;
    } else {
        val += perishable * v_p;
        val += (useful_food - perishable) * v_d;
    }
    val += min(other, people) * v_o;

    return val;
}

double trip_cost(const Trip& trip, int heli_id) {
    if (trip.stops.empty()) return 0.0;
    return helis[heli_id].F + helis[heli_id].alpha * trip.distance;
}

State neighbor_swap_villages(const State& state) {
    State new_state = state;

    if (H < 2) return new_state; // need at least 2 helicopters

    int h1 = rand() % H, h2 = rand() % H;
    if (h1 == h2) return new_state;

    if (new_state.helis[h1].trips.empty() || new_state.helis[h2].trips.empty()) 
        return new_state;

    Trip& trip1 = new_state.helis[h1].trips[rand() % new_state.helis[h1].trips.size()];
    Trip& trip2 = new_state.helis[h2].trips[rand() % new_state.helis[h2].trips.size()];
    if (trip1.stops.empty() || trip2.stops.empty()) return new_state;

    int i1 = rand() % trip1.stops.size();
    int i2 = rand() % trip2.stops.size();

    Delivery old1 = trip1.stops[i1];
    Delivery old2 = trip2.stops[i2];

    int v1 = old1.village - 1;
    int v2 = old2.village - 1;

    // -------- save old contributions --------
    double old_val_v1 = village_value(v1, new_state.delivered[v1]);
    double old_val_v2 = village_value(v2, new_state.delivered[v2]);
    double old_cost1 = trip_cost(trip1, h1);
    double old_cost2 = trip_cost(trip2, h2);

    // -------- update delivered totals --------
    auto adjust_delivered = [&](Delivery d, int sign) {
        new_state.delivered[d.village-1][0] += sign*d.d;
        new_state.delivered[d.village-1][1] += sign*d.p;
        new_state.delivered[d.village-1][2] += sign*d.o;
    };
    adjust_delivered(old1, -1);
    adjust_delivered(old2, -1);

    swap(trip1.stops[i1], trip2.stops[i2]);

    adjust_delivered(trip1.stops[i1], +1);
    adjust_delivered(trip2.stops[i2], +1);

    // -------- update trip distances incrementally --------
    auto update_trip_distance = [&](int h, Trip& trip, int idx, Delivery oldD, Delivery newD) {
        double delta = 0.0;
        pair<double,double> home = cities[helis[h].home_city-1];

        pair<double,double> prev = (idx==0) ? home : 
            make_pair(villages[trip.stops[idx-1].village-1].x, villages[trip.stops[idx-1].village-1].y);

        pair<double,double> next = (idx==trip.stops.size()-1) ? home :
            make_pair(villages[trip.stops[idx+1].village-1].x, villages[trip.stops[idx+1].village-1].y);

        auto pos_old = make_pair(villages[oldD.village-1].x, villages[oldD.village-1].y);
        auto pos_new = make_pair(villages[newD.village-1].x, villages[newD.village-1].y);

        delta -= calculate_distance(prev,pos_old) + calculate_distance(pos_old,next);
        delta += calculate_distance(prev,pos_new) + calculate_distance(pos_new,next);

        trip.distance += delta;
        return delta;
    };

    double delta1 = update_trip_distance(h1, trip1, i1, old1, trip1.stops[i1]);
    double delta2 = update_trip_distance(h2, trip2, i2, old2, trip2.stops[i2]);

    // -------- update trip value incrementally --------
    auto delivery_value = [&](Delivery d) {
        return d.d*v_d + d.p*v_p + d.o*v_o;
    };
    trip1.value += delivery_value(trip1.stops[i1]) - delivery_value(old1);
    trip2.value += delivery_value(trip2.stops[i2]) - delivery_value(old2);

    // -------- update trip weight incrementally --------
    auto delivery_weight = [&](Delivery d) {
        return d.d*w_d + d.p*w_p + d.o*w_o;
    };
    trip1.weight += delivery_weight(trip1.stops[i1]) - delivery_weight(old1);
    trip2.weight += delivery_weight(trip2.stops[i2]) - delivery_weight(old2);

    // -------- update heli total distances incrementally --------
    new_state.helis[h1].total_distance += delta1;
    new_state.helis[h2].total_distance += delta2;

    // -------- recompute only affected objective contributions --------
    double new_val_v1 = village_value(v1, new_state.delivered[v1]);
    double new_val_v2 = village_value(v2, new_state.delivered[v2]);
    double new_cost1 = trip_cost(trip1, h1);
    double new_cost2 = trip_cost(trip2, h2);

    new_state.objective = state.objective
                        - old_val_v1 - old_val_v2
                        + new_val_v1 + new_val_v2
                        - old_cost1 - old_cost2
                        + new_cost1 + new_cost2;

    if(new_state.helis[h1].total_distance > DMax + 1e-9 || new_state.helis[h2].total_distance > DMax + 1e-9){
        new_state.objective = -INFINITY;
    }
    if(trip1.weight > helis[h1].w_cap + 1e-9 || trip2.weight > helis[h2].w_cap + 1e-9){
        new_state.objective = -INFINITY;
    }
    if(trip1.distance > helis[h1].dcap + 1e-9 || trip2.distance > helis[h2].dcap + 1e-9){
        new_state.objective = -INFINITY;
    }
    // new_state.objective = obj_func(new_state); // double-check

    return new_state;
}


State neighbor_reassign_village(const State& state) {
    State new_state = state;
    if (H == 0) return new_state;

    // Find all non-empty deliveries
    vector<tuple<int, int, int>> candidates; // (heli, trip, delivery_idx)
    for (int h = 0; h < H; h++) {
        for (int t = 0; t < (int)new_state.helis[h].trips.size(); t++) {
            for (int d = 0; d < (int)new_state.helis[h].trips[t].stops.size(); d++) {
                candidates.push_back({h, t, d});
            }
        }
    }
    
    if (candidates.empty()) return new_state;

    int rand_idx = rand() % candidates.size();
    auto [h1, t1, d_idx] = candidates[rand_idx];
    
    Trip& source_trip = new_state.helis[h1].trips[t1];
    Delivery moved = source_trip.stops[d_idx];
    int v = moved.village - 1;

    int h2 = rand() % H;
    
    // Avoid degenerate case
    if (h1 == h2 && new_state.helis[h1].trips.size() == 1 && source_trip.stops.size() == 1) {
        return new_state;
    }

    // -------- Save OLD values for incremental update --------
    double old_village_value = village_value(v, new_state.delivered[v]);
    double old_cost1 = (source_trip.stops.size() == 1) ? 0.0 : (helis[h1].F + helis[h1].alpha * source_trip.distance);
    
    // -------- Remove from source trip --------
    new_state.delivered[v][0] -= moved.d;
    new_state.delivered[v][1] -= moved.p;
    new_state.delivered[v][2] -= moved.o;

    // Update source trip
    if (source_trip.stops.size() == 1) {
        // Trip becomes empty
        new_state.helis[h1].total_distance -= source_trip.distance;
        source_trip.distance = 0;
        source_trip.weight = 0;
        source_trip.value = 0;
        source_trip.stops.clear();
    } else {
        // CALCULATE POSITIONS BEFORE MODIFYING THE VECTOR
        pair<double,double> home1 = cities[helis[h1].home_city-1];
        
        pair<double,double> prev = (d_idx == 0) ? home1 : 
            make_pair(villages[source_trip.stops[d_idx-1].village-1].x, villages[source_trip.stops[d_idx-1].village-1].y);
        pair<double,double> next = (d_idx == source_trip.stops.size()-1) ? home1 :
            make_pair(villages[source_trip.stops[d_idx+1].village-1].x, villages[source_trip.stops[d_idx+1].village-1].y);
        auto pos_moved = make_pair(villages[moved.village-1].x, villages[moved.village-1].y);

        double delta = -calculate_distance(prev, pos_moved) - calculate_distance(pos_moved, next)
                       + calculate_distance(prev, next);
        
        source_trip.distance += delta;
        new_state.helis[h1].total_distance += delta;
        
        // Update weight and value
        source_trip.weight -= moved.d * w_d + moved.p * w_p + moved.o * w_o;
        source_trip.value -= moved.d * v_d + moved.p * v_p + moved.o * v_o;
        
        // Remove delivery AFTER calculating positions
        source_trip.stops.erase(source_trip.stops.begin() + d_idx);
    }

    // -------- Add to target helicopter --------
    Trip* target_trip_ptr;
    bool target_was_empty = false;
    
    if (new_state.helis[h2].trips.empty() || (rand() % 3 == 0)) {
        new_state.helis[h2].trips.push_back(Trip());
        target_trip_ptr = &new_state.helis[h2].trips.back();
        target_was_empty = true;
    } else {
        target_trip_ptr = &new_state.helis[h2].trips[rand() % new_state.helis[h2].trips.size()];
        target_was_empty = target_trip_ptr->stops.empty();
    }
    
    Trip& target_trip = *target_trip_ptr;
    double old_cost2 = target_was_empty ? 0.0 : (helis[h2].F + helis[h2].alpha * target_trip.distance);

    // Insert delivery
    int pos = rand() % (target_trip.stops.size() + 1);
    target_trip.stops.insert(target_trip.stops.begin() + pos, moved);

    // Update target trip
    if (target_trip.stops.size() == 1) {
        // First delivery in empty trip
        pair<double,double> home2 = cities[helis[h2].home_city-1];
        auto pos_moved = make_pair(villages[moved.village-1].x, villages[moved.village-1].y);
        target_trip.distance = 2 * calculate_distance(home2, pos_moved);
        new_state.helis[h2].total_distance += target_trip.distance;
    } else {
        // Insert into existing route
        pair<double,double> home2 = cities[helis[h2].home_city-1];
        
        pair<double,double> prev = (pos == 0) ? home2 :
            make_pair(villages[target_trip.stops[pos-1].village-1].x, villages[target_trip.stops[pos-1].village-1].y);
        pair<double,double> next = (pos == target_trip.stops.size()-1) ? home2 :
            make_pair(villages[target_trip.stops[pos+1].village-1].x, villages[target_trip.stops[pos+1].village-1].y);
        auto pos_moved = make_pair(villages[moved.village-1].x, villages[moved.village-1].y);

        double delta = -calculate_distance(prev, next)
                       + calculate_distance(prev, pos_moved) + calculate_distance(pos_moved, next);
        target_trip.distance += delta;
        new_state.helis[h2].total_distance += delta;
    }

    target_trip.weight += moved.d * w_d + moved.p * w_p + moved.o * w_o;
    target_trip.value += moved.d * v_d + moved.p * v_p + moved.o * v_o;

    // -------- Update delivered totals (add back) --------
    new_state.delivered[v][0] += moved.d;
    new_state.delivered[v][1] += moved.p;
    new_state.delivered[v][2] += moved.o;

    // -------- Clean up empty trips from source helicopter --------
    auto& trips = new_state.helis[h1].trips;
    trips.erase(remove_if(trips.begin(), trips.end(), 
                         [](const Trip& t) { return t.stops.empty(); }), 
                trips.end());

    // -------- Calculate NEW values for incremental update --------
    double new_village_value = village_value(v, new_state.delivered[v]);
    double new_cost1 = 0.0;
    if (!new_state.helis[h1].trips.empty()) {
        // Find the trip that was modified (if it still exists)
        bool found_modified_trip = false;
        for (const Trip& trip : new_state.helis[h1].trips) {
            if (!trip.stops.empty() && trip.distance > 0) {
                new_cost1 += helis[h1].F + helis[h1].alpha * trip.distance;
            }
        }
    }
    
    double new_cost2 = helis[h2].F + helis[h2].alpha * target_trip.distance;

    // -------- Update objective incrementally --------
    new_state.objective = state.objective
                        - old_village_value + new_village_value
                        - old_cost1 - old_cost2
                        + new_cost1 + new_cost2;

    new_state.objective = obj_func(new_state); // double-check

    return new_state;
}

State neighbor_reassign_village2(const State& state) {
    State new_state = state;
    if (H == 0) return new_state;

    int h1 = rand() % H;
    if (new_state.helis[h1].trips.empty()) return new_state;

    Trip& trip1 = new_state.helis[h1].trips[rand() % new_state.helis[h1].trips.size()];
    if (trip1.stops.empty()) return new_state;

    int idx = rand() % trip1.stops.size();
    Delivery moved = trip1.stops[idx];
    int v = moved.village - 1;

    // -------- Save old contributions --------
    double old_val_v = village_value(v, new_state.delivered[v]);
    double old_cost1 = trip_cost(trip1, h1);
    double old_cost2 = 0.0;

    int h2 = rand() % H;
    if (h2 == h1 && new_state.helis[h1].trips.size() == 1 && trip1.stops.size() == 1)
        return new_state; // avoid degenerate

    Trip* trip2_ptr = nullptr;
    bool new_trip_created = false;
    if (new_state.helis[h2].trips.empty() || (rand()%2==0)) {
        // create new trip if none exists or sometimes randomly
        new_state.helis[h2].trips.push_back(Trip());
        trip2_ptr = &new_state.helis[h2].trips.back();
        new_trip_created = true;
    } else {
        trip2_ptr = &new_state.helis[h2].trips[rand() % new_state.helis[h2].trips.size()];
    }
    Trip& trip2 = *trip2_ptr;
    old_cost2 = trip_cost(trip2, h2);

    // -------- Update delivered totals --------
    new_state.delivered[v][0] -= moved.d;
    new_state.delivered[v][1] -= moved.p;
    new_state.delivered[v][2] -= moved.o;

    // -------- Update trip1 (remove delivery) --------
    {
        pair<double,double> home = cities[helis[h1].home_city-1];
        pair<double,double> prev = (idx==0) ? home : make_pair(villages[trip1.stops[idx-1].village-1].x, villages[trip1.stops[idx-1].village-1].y);
        pair<double,double> next = (idx==trip1.stops.size()-1) ? home : make_pair(villages[trip1.stops[idx+1].village-1].x, villages[trip1.stops[idx+1].village-1].y);
        auto pos_moved = make_pair(villages[moved.village-1].x, villages[moved.village-1].y);

        double delta = -calculate_distance(prev,pos_moved) - calculate_distance(pos_moved,next)
                       + calculate_distance(prev,next);
        trip1.distance += delta;
        new_state.helis[h1].total_distance += delta;
    }

    auto delivery_value = [&](const Delivery& d) {
        return d.d*v_d + d.p*v_p + d.o*v_o;
    };

    auto delivery_weight = [&](const Delivery& d) {
        return d.d*w_d + d.p*w_p + d.o*w_o;
    };

    trip1.value -= delivery_value(moved);
    trip1.weight -= delivery_weight(moved);

    trip1.stops.erase(trip1.stops.begin() + idx);

    // -------- Update trip2 (insert delivery) --------
    int pos = rand() % (trip2.stops.size() + 1);
    {
        pair<double,double> home = cities[helis[h2].home_city-1];
        pair<double,double> prev = (pos==0) ? home : make_pair(villages[trip2.stops[pos-1].village-1].x, villages[trip2.stops[pos-1].village-1].y);
        pair<double,double> next = (pos==trip2.stops.size()) ? home : make_pair(villages[trip2.stops[pos].village-1].x, villages[trip2.stops[pos].village-1].y);
        auto pos_moved = make_pair(villages[moved.village-1].x, villages[moved.village-1].y);

        double delta = -calculate_distance(prev,next)
                       + calculate_distance(prev,pos_moved) + calculate_distance(pos_moved,next);
        trip2.distance += delta;
        new_state.helis[h2].total_distance += delta;
    }

    trip2.stops.insert(trip2.stops.begin() + pos, moved);
    trip2.value += delivery_value(moved);
    trip2.weight += delivery_weight(moved);

    // -------- Update delivered totals again (for new placement) --------
    new_state.delivered[v][0] += moved.d;
    new_state.delivered[v][1] += moved.p;
    new_state.delivered[v][2] += moved.o;

    // -------- Recompute affected contributions incrementally --------
    double new_val_v = village_value(v, new_state.delivered[v]);
    double new_cost1 = trip_cost(trip1, h1);
    double new_cost2 = trip_cost(trip2, h2);

    new_state.objective = state.objective
                        - old_val_v + new_val_v
                        - old_cost1 - old_cost2
                        + new_cost1 + new_cost2;

    new_state.objective = obj_func(new_state); // double-check

    return new_state;
}



//2 opt method to optimise dcap thing
State neighbor_2opt(const State& state) {
    State new_state = state;
    if (H == 0) return new_state;

    int h = rand() % H;
    if (new_state.helis[h].trips.empty()) return new_state;

    Trip& trip = new_state.helis[h].trips[rand() % new_state.helis[h].trips.size()];
    int n = trip.stops.size();
    if (n < 4) return new_state; // 2-opt needs >= 4

    int i = rand() % (n - 1);
    int j = i + 1 + rand() % (n - i - 1);

    // -------- Save old trip cost --------
    double old_cost = trip_cost(trip, h);

    // -------- Compute distance delta --------
    pair<double,double> home = cities[helis[h].home_city-1];

    auto getPos = [&](int idx) {
        if (idx == -1) return home;
        if (idx == n) return home;
        return make_pair(villages[trip.stops[idx].village-1].x,
                         villages[trip.stops[idx].village-1].y);
    };

    pair<double,double> pi_1 = getPos(i-1);
    pair<double,double> pi   = getPos(i);
    pair<double,double> pj_1 = getPos(j-1);
    pair<double,double> pj   = getPos(j);

    double delta = 0.0;
    delta -= calculate_distance(pi_1, pi);
    delta -= calculate_distance(pj_1, pj);
    delta += calculate_distance(pi_1, pj_1);
    delta += calculate_distance(pi, pj);

    trip.distance += delta;
    new_state.helis[h].total_distance += delta;

    // -------- Apply the actual 2-opt reversal --------
    reverse(trip.stops.begin() + i, trip.stops.begin() + j);

    // -------- Update objective incrementally --------
    double new_cost = trip_cost(trip, h);
    new_state.objective = state.objective - old_cost + new_cost;

    if(new_state.helis[h].total_distance > DMax + 1e-9){
        new_state.objective = -INFINITY;
    }
    if(trip.weight > helis[h].w_cap + 1e-9){
        new_state.objective = -INFINITY;
    }
    if(trip.distance > helis[h].dcap + 1e-9){
        new_state.objective = -INFINITY;
    }
    // new_state.objective = obj_func(new_state); // double-check

    return new_state;
}

State neighbor_swap_adjacent(const State& state) {
    State new_state = state;

    int h = rand() % H;
    if (new_state.helis[h].trips.empty()) return new_state;

    Trip& trip = new_state.helis[h].trips[rand() % new_state.helis[h].trips.size()];
    int n = trip.stops.size();
    if (n < 2) return new_state;

    int i = rand() % (n - 1);  // swap i and i+1
    Delivery& A = trip.stops[i];
    Delivery& B = trip.stops[i+1];

    // -------- Save old cost --------
    double old_cost = trip_cost(trip, h);

    // -------- Compute distance delta --------
    pair<double,double> home = cities[helis[h].home_city-1];
    auto getPos = [&](int idx) {
        if (idx == -1) return home;
        if (idx == n) return home;
        return make_pair(villages[trip.stops[idx].village-1].x,
                         villages[trip.stops[idx].village-1].y);
    };

    pair<double,double> prev = getPos(i-1);
    pair<double,double> next = getPos(i+2);

    auto posA = make_pair(villages[A.village-1].x, villages[A.village-1].y);
    auto posB = make_pair(villages[B.village-1].x, villages[B.village-1].y);

    double delta = 0.0;
    delta -= calculate_distance(prev, posA);
    delta -= calculate_distance(posA, posB);
    delta -= calculate_distance(posB, next);

    delta += calculate_distance(prev, posB);
    delta += calculate_distance(posB, posA);
    delta += calculate_distance(posA, next);

    trip.distance += delta;
    new_state.helis[h].total_distance += delta;

    // -------- Actually swap deliveries --------
    swap(A, B);

    // -------- Update objective incrementally --------
    double new_cost = trip_cost(trip, h);
    new_state.objective = state.objective - old_cost + new_cost;


    if(new_state.helis[h].total_distance > DMax + 1e-9 || trip.weight > helis[h].w_cap + 1e-9 || trip.distance > helis[h].dcap + 1e-9){
        new_state.objective = -INFINITY;
    }
    //new_state.objective = obj_func(new_state); // double-check

    return new_state;
}

State neighbor_food_mix(const State& state) {
    State new_state = state;
    if (H == 0) return new_state;

    int h = rand() % H;
    if (new_state.helis[h].trips.empty()) return new_state;

    Trip& trip = new_state.helis[h].trips[rand() % new_state.helis[h].trips.size()];
    if (trip.stops.empty()) return new_state;

    int idx = rand() % trip.stops.size();
    Delivery& d = trip.stops[idx];
    if (d.d == 0 && d.p == 0) return new_state; // nothing to swap
    int v = d.village - 1;

    // -------- Save old contributions --------
    double old_val_v = village_value(v, new_state.delivered[v]);
    double old_cost = trip_cost(trip, h); // cost doesn’t change, but we keep formality

    Delivery oldD = d;

    // -------- Apply modification --------
    if (d.d > 0) {
        d.d -= 1;
        d.p += 1;
    } else if (d.p > 0) {
        d.p -= 1;
        d.d += 1;
    } else {
        return new_state; // nothing to swap
    }

    // -------- Update delivered totals --------
    new_state.delivered[v][0] += (d.d - oldD.d);
    new_state.delivered[v][1] += (d.p - oldD.p);

    // -------- Update trip weight incrementally --------
    trip.weight += (d.d - oldD.d) * w_d + (d.p - oldD.p) * w_p;

    // -------- Update trip value incrementally --------
    trip.value += (d.d - oldD.d) * v_d + (d.p - oldD.p) * v_p;

    // -------- Recompute affected contributions --------
    double new_val_v = village_value(v, new_state.delivered[v]);
    double new_cost = trip_cost(trip, h); // unchanged

    new_state.objective = state.objective
                        - old_val_v + new_val_v
                        - old_cost + new_cost;  // effectively cancels, since cost same

    if(new_state.helis[h].total_distance > DMax + 1e-9){
        new_state.objective = -INFINITY;
    }
    if(trip.weight > helis[h].w_cap + 1e-9){
        new_state.objective = -INFINITY;
    }
    if(trip.distance > helis[h].dcap + 1e-9){
        new_state.objective = -INFINITY;
    }
    // new_state.objective = obj_func(new_state); // double-check

    return new_state;
}


State neighbor_rebalance_other(const State& state) {
    State new_state = state;
    if (H == 0) return new_state;

    int h = rand() % H;
    if (new_state.helis[h].trips.empty()) return new_state;

    Trip& trip = new_state.helis[h].trips[rand() % new_state.helis[h].trips.size()];
    int n = trip.stops.size();
    if (n < 2) return new_state;

    int i = rand() % n;
    int j = (i + 1 + rand() % (n - 1)) % n;

    if (trip.stops[i].o == 0) return new_state; // nothing to move

    int vi = trip.stops[i].village - 1;
    int vj = trip.stops[j].village - 1;

    // -------- Save old contributions --------
    double old_val_i = village_value(vi, new_state.delivered[vi]);
    double old_val_j = village_value(vj, new_state.delivered[vj]);

    double old_cost = trip_cost(trip, h); // unchanged, but for consistency

    // -------- Apply modification --------
    trip.stops[i].o -= 1;
    trip.stops[j].o += 1;

    // -------- Update delivered totals --------
    new_state.delivered[vi][2] -= 1;
    new_state.delivered[vj][2] += 1;

    // -------- Recompute affected contributions --------
    double new_val_i = village_value(vi, new_state.delivered[vi]);
    double new_val_j = village_value(vj, new_state.delivered[vj]);
    double new_cost  = trip_cost(trip, h); // unchanged

    new_state.objective = state.objective
                        - old_val_i - old_val_j
                        + new_val_i + new_val_j
                        - old_cost + new_cost;

    if(new_state.helis[h].total_distance > DMax + 1e-9 || trip.weight > helis[h].w_cap + 1e-9 || trip.distance > helis[h].dcap + 1e-9){
        new_state.objective = -INFINITY;
    }
    //new_state.objective = obj_func(new_state); // double-check

    return new_state;
}


